#!/usr/bin/env node
/**
 * Verify every ArtCraft DSH plugin.
 *
 * Checks, per plugin package:
 *   1. the package manifest is well formed and its entry point exists;
 *   2. the craft profile resolves and the craft CLI is discovered;
 *   3. the craft's live command catalog loads;
 *   4. the tool set is complete for that craft;
 *   5. a real headless command runs through the plugin's own `run` tool and
 *      produces the artifact the profile promised.
 *
 * Also checks cross-cutting invariants: the kernel's generated `lib/` is not
 * stale, and every plugin's bare imports resolve to the harness's copies.
 *
 * Usage:
 *   node scripts/verify.mjs                 # all plugins
 *   node scripts/verify.mjs gridcraft ...   # named crafts only
 *   node scripts/verify.mjs --quick         # skip the live headless runs
 * @module scripts/verify
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pluginsDir = join(root, 'dsh-plugins')
const quick = process.argv.includes('--quick')
const requested = process.argv.slice(2).filter(arg => !arg.startsWith('--'))

// Every plugin package carries its own inlined copy of the kernel, so the
// verifier loads what actually ships rather than a shared workspace copy.
const inlinedKit = async (craft) => await import(join(pluginsDir, `plugin-${craft}`, 'src', 'kit', 'index.js'))

const failures = []
const notes = []
const fail = (craft, message) => { failures.push(`${craft}: ${message}`); return false }

/**
 * A headless smoke scenario per craft — each one was run against the real CLI
 * while the profile was written, so a failure here means a regression, not an
 * unverified guess. `expect` names the artifact that must appear and be non-empty.
 */
const SCENARIOS = {
  // `run` takes the drawing positionally and has no `--save`-less export.
  cadcraft: { sample: true, save: 'out.dxf', export: 'out.png' },
  gridcraft: { sample: 'budget', commands: [{ id: 'cell.set', json: { cell: 'Z1', input: 'dsh' } }], save: 'out.xlsx' },
  soundcraft: { sample: true, commands: [{ id: 'mix.volume', json: { track: 'Kick', db: -6 } }], export: 'out.wav', expect: 'out.wav' },
  deckcraft: { sample: true, commands: [{ id: 'slide.new', json: { layout: 'titleOnly', title: 'dsh' } }], save: 'out.deckcraft' },
  wordcraft: { commands: [{ id: 'text.insert', json: { text: 'dsh verification' } }], save: 'out.docx' },
  // PhotoCraft `run` needs exactly one of <file> or --new <json>; `file.new`
  // on the freshly created document is what gives it the requested size.
  photocraft: { sample: true, commands: [{ id: 'file.new', json: { width: 64, height: 64 } }], save: 'out.png' },
  // LightCraft: --demo is the sample, export writes the artifact, commands are key=value.
  // LightCraft writes the artifact to the path it is given, so the file carries
  // whatever extension the caller named; there is no extension-derived output.
  // LightCraft's demo library exports as-is; a develop command needs a photo
  // selected first, which is a separate workflow rather than a smoke test.
  lightcraft: { sample: true, commands: [{ id: 'app.export', json: { path: 'OUT', longEdge: 400 } }], export: 'out.jpg', expect: 'out.bin' },
  // PdfCraft runs exactly one tool per call and writes through doc_save, so the
  // scenario is a sequence of separate invocations rather than one command list.
  // PdfCraft holds one document per process, so this scenario is two separate
  // calls: the kernel replays the first call's commands to rebuild the
  // document, then applies the save. That is the documented cross-call flow.
  pdfcraft: {
    calls: [
      { commands: [{ id: 'doc_create', json: { from: 'text', text: 'dsh verification' } }] },
      { commands: [{ id: 'doc_save', json: { path: 'OUT', doc: 1 } }] },
    ],
    expect: 'out.pdf',
  },
  // EffectCraft writes through its own file.saveAs command; there is no --save.
  effectcraft: { commands: [{ id: 'file.saveAs', json: { path: 'OUT' } }], save: 'out.ecproj' },
  // FilmCraft takes a JSONL script file, generated by the kernel.
  // FilmCraft's kernel-generated JSONL script creates the project; the profile
  // declares `--save-as ARTIFACT`, which the kernel places before `run`.
  filmcraft: { commands: [{ id: 'file.newProject', json: { name: 'dsh-verify' } }, { id: 'file.newSequence', json: { name: 'seq' } }], expect: 'out.fcproj', save: 'out.fcproj' },
  // DesignCraft has no --save on `run` and no document-inspect verb.
  designcraft: { sample: true, commands: [{ id: 'file.new', json: { preset: 'A4', pages: 1 } }], export: 'out.pdf' },
  vectorcraft: { commands: [{ id: 'file.new', json: {} }], save: 'out.svg' },
}

const plugins = readdirSync(pluginsDir, { withFileTypes: true })
  .filter(entry => entry.isDirectory() && entry.name.startsWith('plugin-'))
  .map(entry => ({ dir: join(pluginsDir, entry.name), craft: entry.name.slice('plugin-'.length) }))
  .filter(plugin => requested.length === 0 || requested.includes(plugin.craft))
  .sort((a, b) => a.craft.localeCompare(b.craft))

if (plugins.length === 0) {
  console.error('no plugin packages found')
  process.exit(1)
}

// --- cross-cutting: the generated kernel must not be stale -----------------
try {
  execFileSync(process.execPath, [join(root, 'scripts', 'build-kit.mjs'), '--check'], { stdio: 'pipe' })
  notes.push('craft-kit/lib is up to date')
} catch (error) {
  failures.push(`craft-kit/lib is stale: ${String(error.stdout ?? error.message).trim()}`)
}

const results = []
for (const plugin of plugins) {
  const { craft, dir } = plugin
  const manifestPath = join(dir, 'package.json')
  if (!existsSync(manifestPath)) { fail(craft, 'no package.json'); continue }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  if (manifest.name !== `dsh-artcraft-plugin-${craft}`) fail(craft, `unexpected package name ${manifest.name}`)
  const entry = manifest.exports?.['.']
  const entryPath = typeof entry === 'string' ? join(dir, entry) : undefined
  if (entryPath === undefined || !existsSync(entryPath)) { fail(craft, `entry point missing: ${entry}`); continue }

  // A published plugin must be self-contained: its kernel travels with it, and
  // the only bare imports it keeps are the two the harness installation routes.
  const kitDir = join(dir, 'src', 'kit')
  if (!existsSync(join(kitDir, 'index.js'))) fail(craft, 'no inlined kernel at src/kit/index.js — run scripts/build-kit.mjs')
  const entrySource = readFileSync(entryPath, 'utf8')
  const bareImports = [...entrySource.matchAll(/from '([^.'][^']*)'/g)].map(match => match[1])
  for (const specifier of bareImports) {
    if (!specifier.startsWith('@deepseek-ai/')) {
      fail(craft, `installed package cannot resolve ${specifier}: only @deepseek-ai/* is routed to the harness`)
    }
  }
  if (!bareImports.some(specifier => specifier === '@deepseek-ai/dsh-tools')) {
    fail(craft, 'entry does not import defineTool from @deepseek-ai/dsh-tools')
  }

  // `dsh.bundle` is what makes the package installable at all.
  const bundlePatch = manifest.dsh?.bundle?.patch
  if (typeof bundlePatch !== 'string') fail(craft, 'package.json declares no dsh.bundle.patch')
  else {
    const patchPath = join(dir, bundlePatch)
    if (!existsSync(patchPath)) fail(craft, `dsh.bundle.patch points at a missing file: ${bundlePatch}`)
    else if (!readFileSync(patchPath, 'utf8').includes(manifest.name)) fail(craft, `${bundlePatch} does not reference ${manifest.name}`)
  }

  const kit = await inlinedKit(craft)
  const profile = kit.profileOf(craft)
  if (profile === undefined) { fail(craft, 'the inlined kernel has no profile for this craft'); continue }

  const runtime = kit.createRuntime(profile, dir, {})
  const binary = runtime.binary()
  if (binary === undefined) { fail(craft, `craft CLI ${profile.bin} not found`); continue }
  const catalog = await runtime.catalog()
  if (catalog.commands.length === 0) { fail(craft, `catalog empty (${catalog.origin}): ${catalog.note ?? ''}`) }

  const tools = kit.createToolSet(runtime)
  const expected = ['run', 'commands', 'describe']
  // Every craft app ships `*-cli mcp`, so the bridge must be built.
  if (profile.mcpArgs !== undefined) expected.push('mcpTools', 'mcpCall', 'mcpStatus')
  if (profile.reads?.some(read => read.name === 'inspect') === true) expected.push('inspect')
  if (profile.reads?.some(read => read.name === 'convert') === true) expected.push('convert')
  for (const name of expected) {
    if (tools[name] === undefined) fail(craft, `tool set is missing "${name}"`)
  }

  let mcpSummary = 'n/a'
  if (profile.mcpArgs !== undefined && tools.mcpTools !== undefined && tools.mcpCall !== undefined) {
    try {
      const listing = await tools.mcpTools.execute({ limit: 5 })
      const count = /—\s*(\d+)\s+tool\(s\)/.exec(listing)?.[1] ?? '?'
      const first = /^([a-z_][\w]*)\s+—/m.exec(listing)?.[1]
      mcpSummary = `${count} tools`
      // Prove a real round trip by calling the first tool the server declares no
      // required arguments for; many tools legitimately need input, so a schema
      // with required fields is skipped rather than mis-called.
      const zeroArg = findZeroArgTool(listing)
      if (zeroArg !== undefined && !quick) {
        const output = await tools.mcpCall.execute({ tool: zeroArg, arguments: {} })
        mcpSummary += output.trim().length > 0 ? ` (${zeroArg} ok)` : ` (${zeroArg} empty)`
      } else {
        mcpSummary += ' (listing ok)'
      }
    } catch (error) {
      mcpSummary = 'FAILED'
      fail(craft, `MCP bridge failed: ${error.message}`)
    }
  }

  const row = {
    craft,
    binary: binary.version ?? binary.path,
    catalog: `${catalog.commands.length} (${catalog.origin})`,
    tools: Object.keys(tools).length,
    mcp: mcpSummary,
    run: 'skipped',
  }

  if (!quick) {
    const scenario = SCENARIOS[craft]
    if (scenario === undefined) {
      row.run = 'no scenario'
    } else {
      const workdir = join(root, '.verify', craft)
      mkdirSync(workdir, { recursive: true })
      const outputName = scenario.expect ?? scenario.save ?? scenario.export ?? 'out.bin'
      const substitute = (value) => value
        .replaceAll('OUT', join(workdir, outputName))
        .replaceAll('FIXTURE', scenario.fixture ?? '')
      const args = { commands: (scenario.commands ?? []).map(command => ({ id: command.id, json: command.json })) }
      if (scenario.sample !== undefined) args.sample = scenario.sample
      if (scenario.save !== undefined) args.save = validateArtifact(scenario.save, workdir)
      if (scenario.export !== undefined) args.export = validateArtifact(scenario.export, workdir)
      if (scenario.extraArgs !== undefined) args.extraArgs = scenario.extraArgs.map(substitute)
      if (scenario.commands !== undefined) {
        args.commands = args.commands.map((command, index) => ({
          id: command.id,
          json: JSON.parse(substitute(JSON.stringify(scenario.commands[index].json ?? {}))),
        }))
      }
      const wanted = outputName
      const wantedPath = wanted === undefined ? undefined : join(workdir, wanted)
      if (wantedPath !== undefined) rmSync(wantedPath, { force: true })
      try {
        // A scenario may need several invocations (PdfCraft is one tool per call);
        // `calls` runs them in order, otherwise the single `args` set is used.
        let output
        if (scenario.scripted !== undefined) {
          // Several commands that must share one process: hand the CLI a script
          // file through `extraArgs`, which is exactly what a real caller does.
          const scriptPath = join(workdir, 'steps.json')
          writeFileSync(scriptPath, JSON.stringify(scenario.scripted.map((command) => ({
            tool: command.id,
            args: JSON.parse(substitute(JSON.stringify(command.json ?? {}))),
          }))))
          output = await tools.run.execute({ extraArgs: ['--script', scriptPath] })
        } else if (scenario.calls === undefined) {
          output = await tools.run.execute(args)
        } else {
          output = (await Promise.all(scenario.calls.map(async (call) => {
            const callArgs = { commands: call.commands.map((command, index) => ({
              id: command.id,
              json: JSON.parse(substitute(JSON.stringify(call.commands[index].json ?? {}))),
            })) }
            return await tools.run.execute(callArgs)
          }))).join('\n---\n')
        }
        const produced = wantedPath !== undefined && existsSync(wantedPath) && statSync(wantedPath).size > 0
        if (produced) {
          row.run = `ok → ${wanted} (${statSync(wantedPath).size} B)`
        } else if (wantedPath === undefined) {
          row.run = 'ok (no artifact declared)'
        } else {
          row.run = `NO ARTIFACT ${wanted}`
          fail(craft, `headless run produced no ${wanted}\n${indent(output)}`)
        }
      } catch (error) {
        row.run = 'FAILED'
        fail(craft, `headless run threw: ${error.message}`)
      }
    }
  }
  results.push(row)
}

const width = Math.max(...results.map(row => row.craft.length), 6)
console.log(`${'craft'.padEnd(width)}  ${'binary'.padEnd(28)}  ${'catalog'.padEnd(13)}  tools  ${'mcp'.padEnd(22)}  run`)
for (const row of results) {
  console.log(`${row.craft.padEnd(width)}  ${String(row.binary).slice(0, 28).padEnd(28)}  ${row.catalog.padEnd(13)}  ${String(row.tools).padEnd(5)}  ${row.mcp.padEnd(22)}  ${row.run}`)
}
for (const note of notes) console.log(`\nnote: ${note}`)

if (failures.length > 0) {
  console.error(`\n${failures.length} failure(s):`)
  for (const failure of failures) console.error(`  - ${failure}`)
  process.exit(1)
}
console.log(`\nall ${results.length} plugin(s) verified`)

/**
 * Find a tool in a rendered `*_mcp_tools` listing that takes no required
 * arguments, so the verifier can call it without inventing inputs.
 * @param listing - the rendered listing text.
 * @returns the first such tool name, or `undefined`.
 */
function findZeroArgTool(listing) {
  const blocks = listing.split(/\n(?=[a-z_][\w]*\s+—)/)
  for (const block of blocks) {
    const name = /^([a-z_][\w]*)\s+—/.exec(block)?.[1]
    if (name === undefined) continue
    // A rendered schema marks optional properties with `?`; a bare `name: type`
    // line means the server requires it.
    const hasRequired = block.split('\n').slice(1).some(line => /^\s{2}[\w.]+:/.test(line))
    if (!hasRequired) return name
  }
  return undefined
}

/** Absolute path for a declared artifact name, guarding against `..` escapes. */
function validateArtifact(name, workdir) {
  const full = resolve(workdir, name)
  if (!full.startsWith(resolve(workdir))) throw new Error(`artifact escapes the scratch dir: ${name}`)
  return full
}

/** Indent a block for readable failure output. */
function indent(text) {
  return String(text).split('\n').map(line => `      ${line}`).join('\n')
}
